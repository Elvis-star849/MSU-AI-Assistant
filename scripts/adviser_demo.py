"""
Demonstration conversations with the admissions adviser (the same code the chat uses; no model calls, no network).

    python scripts/adviser_demo.py [--out evaluation/results/adviser/DEMO_CONVERSATIONS.md]

Each conversation runs through the real flow (router -> adviser -> entry routes / eligibility engine) in a fresh chat,
exactly as typed by an applicant. The output shows each reply and, for reviewers, the question the adviser chose next.
"""
import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("HF_HUB_OFFLINE", "1")

from src.admissions_flow import handle_message  # noqa: E402
from src.conversation import ChatSession  # noqa: E402

CONVERSATIONS = [
    ("1. The reported example: O Levels and age, then a complete conversation",
     ["I have 5 O-Level passes including Maths and English, and I'm 30 years old. What programme can I do?",
      "I only have O-Levels.", "I have worked for 8 years.", "In IT", "Yes", "Can I study Computer Science?"]),
    ("2. Mature-entry enquiry from scratch",
     ["What about mature entry?", "I'm 27", "No, only O Levels", "5 O levels including English, Maths and Science",
      "I have worked as a lab technician for 6 years"]),
    ("3. Diploma pathway (special entry)",
     ["What if I don't have A-Levels?", "I also have a diploma.", "Accounting",
      "I have 5 O levels including English and Maths", "I am employed as an accountant"]),
    ("4. A Level applicant: progressive recommendation, correction and a programme question",
     ["I got A, B and C at A Level. What can I study?", "Mathematics, Physics and Chemistry",
      "English B, Maths C, 6 passes", "Sorry, actually Chemistry is A", "Why can't I do Biotechnology?"]),
    ("5. Stale applicant data and a new assessment",
     ["I have Mathematics A, Computer Science A and Economics B, what can I study?",
      "I have 5 O-Level passes including Maths and English, and I'm 30 years old. What programme can I do?",
      "New assessment", "No, only O Levels"]),
    ("6. Somebody else's results, a 24-year-old and no work experience",
     ["I have Mathematics A, Physics B and Chemistry C", "Actually, those were my brother's results.",
      "I only have O levels: 6 passes including English and Maths", "I'm 24", "Female", "No work experience"]),
    ("7. Start a new assessment needs confirmation",
     ["I have History A, Shona B and Literature in English B", "Start a new assessment.", "No, keep my details",
      "Start a new assessment.", "Yes, start a new assessment"]),
]


class Offline:
    llm = settings = None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "evaluation/results/adviser/DEMO_CONVERSATIONS.md"))
    a = ap.parse_args()
    md = ["# Admissions adviser: demonstration conversations", "",
          "Generated by `python scripts/adviser_demo.py` through the real chat flow (router, adviser, entry routes, "
          "eligibility engine) in a fresh chat per conversation. No model call is made on these turns. The live "
          "browser run of the same scenarios is in `logs/e2e_adviser/transcript.md` (copied to "
          "`browser_transcript.md` beside this file).", ""]
    for title, messages in CONVERSATIONS:
        chat = ChatSession()
        md += [f"## {title}", ""]
        for m in messages:
            turn = handle_message(chat, Offline(), m, log_path=None)
            answer = turn.flow.answer if turn.flow is not None and turn.flow.answer else (turn.result.answer or "")
            reply = turn.flow.data if turn.flow is not None else None
            meta = [f"route: {turn.path}"]
            if reply is not None and getattr(reply, "asked", None):
                meta.append(f"next question: {reply.asked}")
            if reply is not None and getattr(reply, "quick_replies", None):
                meta.append("buttons: " + " | ".join(reply.quick_replies))
            md += [f"**Applicant:** {m}", "", "**Assistant:**", "", answer.strip(), "",
                   f"<sub>{' · '.join(meta)}</sub>", ""]
        md += ["---", ""]
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(md), encoding="utf-8")
    print("wrote", out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
