import sys;sys.path.insert(0,'.')
from eligibility_checker import check,parse_pairs
def names(r,k): return {x["programme"] for x in r[k]}
def has(r,sub,keys=("eligible","eligible_confirm")):
    return any(sub in x["programme"] for k in keys for x in r[k])
def bad(r,sub): return any(sub in x["programme"] for x in r["not_eligible"])
T=[];ok=0
def t(name,cond):
    global ok; T.append((name,cond)); ok+=cond
r=check(parse_pairs("Mathematics=A,Computer Science=A,Economics=B"),parse_pairs("English=B,Mathematics=C,passes=6"))
t("points=14",r["a_level_points_best_three"]==14)
t("CS BSc eligible",has(r,"Degree in Computer Science"))
t("Software Eng eligible",has(r,"Software Engineering"))
t("Cybersecurity eligible",has(r,"Cybersecurity"))
t("Actuarial eligible (14>=10, Maths A)",has(r,"Actuarial"))
t("Economics BCom eligible",has(r,"Economics and Econometric"))
t("Biotech NOT eligible (needs Biology/Chemistry)",bad(r,"Biotechnology"))
t("Mechanical Eng NOT eligible (needs Physics)",bad(r,"Mechanical Engineering"))
t("Applied Accounting NOT eligible (needs Accounting)",bad(r,"Applied Accounting"))
t("LLB NOT eligible",bad(r,"Laws"))
t("Telecom needs Science O Level confirmed",any("Telecommunications Engineering"==x["programme"].split("Degree in ")[-1].split(" (")[0] for x in r["eligible_confirm"]))
r=check(parse_pairs("Mathematics=F,Physics=A,Chemistry=B"))
t("F is a fail: Maths not counted",r["failed_a_level_grades"]==["Mathematics (F)"] and bad(r,"Biotechnology") )
t("O grade is a fail too",check(parse_pairs("Mathematics=O,Physics=A,Chemistry=B"))["failed_a_level_grades"]==["Mathematics (O)"])
r=check(parse_pairs("Mathematics=B,Economics=E"))
t("Actuarial needs 10 points",bad(r,"Actuarial"))
r=check(parse_pairs("Mathematics=B,Physics=B,Chemistry=C"))
t("Actuarial 11 points ok",has(r,"Actuarial"))
r=check(parse_pairs("Mathematics=C,Physics=A,Chemistry=A"))
t("Actuarial needs B in Maths",bad(r,"Actuarial"))
r=check(parse_pairs("Economics=A,Accounting=B,Business Studies=C"),parse_pairs("English=C,Mathematics=D,passes=5"))
t("BCom Economics fails with O Maths D",bad(r,"Economics and Econometric"))
r=check(parse_pairs("Economics=A,Accounting=B,Business Studies=C"),parse_pairs("English=C,Mathematics=C,passes=5"))
t("Applied Accounting eligible",has(r,"Applied Accounting"))
t("Marketing Management needs O Maths B -> fails at C",bad(r,"Marketing Management"))
r=check(parse_pairs("History=A,Shona=B,Sociology=B"),parse_pairs("English=B,Mathematics=B,passes=6"))
t("LLB eligible",has(r,"Laws"))
r=check(parse_pairs("History=A,Shona=B,Sociology=C"),parse_pairs("English=B,Mathematics=B,passes=6"))
t("LLB needs B on the Arts subject",bad(r,"Laws"))
r=check(parse_pairs("History=A,Shona=B,Sociology=B"),parse_pairs("English=B,Mathematics=C,passes=6"))
t("LLB needs O Maths B",bad(r,"Laws"))
r=check(parse_pairs("History=A,Shona=B"),parse_pairs("English=B,Mathematics=B,passes=4"))
t("fewer than 5 O Level passes rejects all A Level routes",len(r["eligible"])==0 and len(r["eligible_confirm"])==0)
r=check(parse_pairs("Mathematics=A"))
t("one A Level pass meets no A Level route (only the 4 O Level-only programmes remain)",len(r["eligible"])+len(r["eligible_confirm"])==4)
r=check(parse_pairs("maths=a,comp sci=b"))
t("aliases and lowercase grades",r["a_level_points_best_three"]==9 and has(r,"Degree in Computer Science"))
for n,c in T: print("PASS" if c else "FAIL",n)
print(ok,"/",len(T))
